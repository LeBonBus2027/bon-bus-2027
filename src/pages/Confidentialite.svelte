<h1 tabindex="-1">Confidentialité</h1>
<p><strong>Nous ne collectons rien.</strong> Ni tes réponses, ni ton classement, ni ton résultat. Tout est calculé dans ton navigateur et disparaît quand tu fermes la page.</p>

<h2>Concrètement</h2>
<ul>
  <li>Aucun compte, aucun formulaire, aucune base de données.</li>
  <li>Aucun cookie, ni publicitaire, ni de mesure d'audience. C'est pour ça qu'il n'y a pas de bandeau.</li>
  <li>Aucun service tiers : pas de police d'écriture externe, pas de statistiques, pas de bouton de réseau social. Ton navigateur ne contacte que notre hébergeur.</li>
  <li>L'image de partage est fabriquée dans ton navigateur. Par défaut, elle n'affiche aucun nom de candidat. Tu choisis où et si tu la publies.</li>
  <li>Le lien partagé mène à la page d'accueil, jamais à ton résultat.</li>
</ul>

<h2>Les journaux de l'hébergeur</h2>
<p>Comme tout site, notre hébergeur, Cloudflare, traite techniquement l'adresse IP des visiteurs pour acheminer les pages et protéger le service contre les attaques. Nous n'avons activé aucun journal ni aucune statistique de visite. Ces traitements ne contiennent aucune réponse ni aucun résultat.</p>

